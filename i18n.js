const messages = { ...MENU_MESSAGES, ...coreMessages };

const englishKeys = new Map();
const localizedKeys = new Map();
for (const [key, [english, chinese]] of Object.entries(messages)) {
  if (!englishKeys.has(english)) englishKeys.set(english, key);
  if (!localizedKeys.has(chinese)) localizedKeys.set(chinese, key);
}

function preferredLocale() {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (SUPPORTED_LOCALES.includes(saved)) return saved;
  } catch { /* Storage can be unavailable in private contexts. */ }
  const browserLanguages = navigator.languages?.length ? navigator.languages : [navigator.language || 'en'];
  return browserLanguages.some((language) => /^zh(?:-|$)/i.test(language)) ? 'zh-CN' : 'en';
}

let activeLocale = preferredLocale();
const listeners = new Set();

function interpolate(value, variables = {}) {
  return value.replace(/\{([\w]+)\}/g, (_, name) => String(variables[name] ?? `{${name}}`));
}

export function getLocale() { return activeLocale; }

export function t(key, variables = {}) {
  const pair = messages[key];
  if (!pair) return interpolate(String(key), variables);
  return interpolate(pair[activeLocale === 'zh-CN' ? 1 : 0], variables);
}

export function setLocale(locale) {
  const next = locale === 'zh-CN' ? 'zh-CN' : 'en';
  if (next === activeLocale) return next;
  activeLocale = next;
  try { localStorage.setItem(LANGUAGE_STORAGE_KEY, next); } catch { /* Keep the selection for this session. */ }
  document.documentElement.lang = next;
  listeners.forEach((listener) => listener(next));
  return next;
}

export function subscribeLocale(listener) {
  listeners.add(listener);
  return () => listeners.delete(listener);
}

export function keyForText(value) {
  return englishKeys.get(value) || localizedKeys.get(value);
}

export function localizeTree(root = document) {
  if (!root) return;
  const documentRoot = root.ownerDocument || (root.nodeType === Node.DOCUMENT_NODE ? root : document);
  const filter = documentRoot.defaultView?.NodeFilter || NodeFilter;
  const walker = documentRoot.createTreeWalker(root, filter.SHOW_TEXT);
  const textNodes = [];
  while (walker.nextNode()) textNodes.push(walker.currentNode);
  textNodes.forEach((node) => {
    if (!node.nodeValue?.trim()) return;
    const key = keyForText(node.nodeValue.trim());
    if (!key) return;
    const leading = node.nodeValue.match(/^\s*/)?.[0] || '';
    const trailing = node.nodeValue.match(/\s*$/)?.[0] || '';
    node.nodeValue = `${leading}${t(key)}${trailing}`;
  });
  const elements = root.querySelectorAll?.('[aria-label], [title], [placeholder]') || [];
  elements.forEach((element) => ['aria-label', 'title', 'placeholder'].forEach((attribute) => {
    const value = element.getAttribute(attribute);
    const key = value && keyForText(value);
    if (key) element.setAttribute(attribute, t(key));
  }));
}

export function applyLocale(root = document) {
  document.documentElement.lang = activeLocale;
  localizeTree(root);
}
